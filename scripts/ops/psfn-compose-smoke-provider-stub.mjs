#!/usr/bin/env node
// ── Compose smoke provider stub (psfn-framework-j3iol) ──
//
// A deterministic OpenAI-compatible HTTP double for the disposable Compose
// smoke stack ONLY. It exists so `npm run smoke:docker` is an honest end-to-end
// check with no provider account and no external egress: the gateway boots with
// a real, gateway-resolved screener credential and one chat turn completes.
//
// It is selected exclusively by the smoke stack's own owner-file fixtures
// (docker/smoke-fixtures/providers.json + models.json), which name the
// `smoke-stub` provider at this service's internal address. No production seed,
// Helm value, or supported Compose path references it, and this file is never
// loaded by the runtime — it is a separate process started by
// docker-compose.smoke.yml. Every fail-closed production path is unchanged: the
// gateway still demands a resolvable credential, still refuses an unscreenable
// intake surface, and still rejects a malformed screener verdict.
//
// Honest-double rules this file keeps:
//   * It authenticates. A request without the exact configured bearer gets 401,
//     so a smoke pass proves the gateway really resolved and presented the
//     credential rather than proving that credentials are optional.
//   * It answers the real wire protocol. pi-ai always sends `stream: true` with
//     `stream_options.include_usage`, so the default path is SSE; a
//     non-streaming request is answered as plain JSON.
//   * It never fabricates a verdict it was not asked for. The intake L2/L3/
//     vision screeners are recognized by their own system prompts and answered
//     with the exact schema each one validates — a benign verdict for benign
//     smoke content. Anything else gets the fixed smoke reply. It performs no
//     classification and must never stand in for a real screener.
//
// Environment (all required; there are no defaults, so a misconfigured stack
// fails immediately instead of listening on a surprising address):
//   PSFN_SMOKE_PROVIDER_STUB_HOST     bind host
//   PSFN_SMOKE_PROVIDER_STUB_PORT     bind port
//   PSFN_SMOKE_PROVIDER_STUB_API_KEY  the bearer the gateway must present
//   PSFN_SMOKE_PROVIDER_STUB_REPLY    the deterministic assistant reply text

import { createServer } from 'node:http';
import process from 'node:process';

const MAX_PORT = 65_535;
const MAX_REQUEST_BYTES = 4 * 1024 * 1024;
const HTTP_OK = 200;
const HTTP_BAD_REQUEST = 400;
const HTTP_UNAUTHORIZED = 401;
const HTTP_NOT_FOUND = 404;
const HTTP_PAYLOAD_TOO_LARGE = 413;
const HTTP_NO_CONTENT = 204;
const MILLISECONDS_PER_SECOND = 1000;

/** Reported token counts. The stub bills nothing; these keep usage accounting well-formed. */
const REPORTED_PROMPT_TOKENS = 128;
const REPORTED_COMPLETION_TOKENS = 32;

function requireEnvironment(name) {
  const value = process.env[name]?.trim();
  if (!value) throw new Error(`${name} is required`);
  return value;
}

const host = requireEnvironment('PSFN_SMOKE_PROVIDER_STUB_HOST');
const portValue = requireEnvironment('PSFN_SMOKE_PROVIDER_STUB_PORT');
const apiKey = requireEnvironment('PSFN_SMOKE_PROVIDER_STUB_API_KEY');
const replyText = requireEnvironment('PSFN_SMOKE_PROVIDER_STUB_REPLY');
if (!/^[1-9]\d*$/.test(portValue) || Number(portValue) > MAX_PORT) {
  throw new Error(`PSFN_SMOKE_PROVIDER_STUB_PORT must be an integer from 1 through ${MAX_PORT}`);
}

// ── Screener recognition ──
// Each intake screener sends its own fixed system prompt and validates a
// distinct JSON schema (src/boundary/gateway/intake/{l2,l3,vision}-screener.ts).
// Match on the opening identity sentence of each prompt; anything else is an
// ordinary completion.
const SCREENER_MARKERS = /** @type {const} */ ({
  l2: 'isolated security classifier',
  l3: 'isolated deep-screening security classifier',
  vision: 'isolated vision screening service',
});

const SMOKE_SUMMARY = 'Benign smoke-stack content generated by the compose smoke harness.';

/** @param {'l2'|'l3'|'vision'} screener */
function screenerVerdict(screener) {
  if (screener === 'l2') {
    return { labels: [], injectionConfidence: 0, summary: SMOKE_SUMMARY };
  }
  if (screener === 'l3') {
    return {
      flagged: false,
      labels: [],
      injectionConfidence: 0,
      summary: SMOKE_SUMMARY,
      contentType: 'smoke harness message',
      keyEntities: [],
      whyFlagged: '',
    };
  }
  return {
    ocrText: '',
    noLegibleText: true,
    description: 'A placeholder image supplied by the compose smoke harness.',
    flags: [],
  };
}

/** @param {unknown} content */
function flattenContent(content) {
  if (typeof content === 'string') return content;
  if (!Array.isArray(content)) return '';
  return content
    .map(part => (part && typeof part === 'object' && typeof part.text === 'string' ? part.text : ''))
    .join('\n');
}

/**
 * Choose the response body for one request. The unit test drives this over real
 * HTTP and feeds each verdict through the framework's own screener validators.
 *
 * @param {{ messages?: unknown }} body
 */
function resolveResponseContent(body) {
  const messages = Array.isArray(body.messages) ? body.messages : [];
  const systemText = messages
    .filter(message => message && typeof message === 'object' && message.role === 'system')
    .map(message => flattenContent(message.content))
    .join('\n')
    .toLowerCase();
  // L3's marker contains L2's, so test the more specific one first.
  if (systemText.includes(SCREENER_MARKERS.l3)) {
    return JSON.stringify(screenerVerdict('l3'));
  }
  if (systemText.includes(SCREENER_MARKERS.vision)) {
    return JSON.stringify(screenerVerdict('vision'));
  }
  if (systemText.includes(SCREENER_MARKERS.l2)) {
    return JSON.stringify(screenerVerdict('l2'));
  }
  return replyText;
}

function usageBlock() {
  return {
    prompt_tokens: REPORTED_PROMPT_TOKENS,
    completion_tokens: REPORTED_COMPLETION_TOKENS,
    total_tokens: REPORTED_PROMPT_TOKENS + REPORTED_COMPLETION_TOKENS,
  };
}

/** @param {import('node:http').ServerResponse} response */
function sendJson(response, status, body) {
  response.writeHead(status, { 'Content-Type': 'application/json' });
  response.end(JSON.stringify(body));
}

function sendError(response, status, message) {
  sendJson(response, status, { error: { message, type: 'psfn_smoke_provider_stub' } });
}

function completionId() {
  return `chatcmpl-psfn-smoke-${Date.now()}`;
}

/** SSE shape pi-ai's openai-completions client consumes (stream_options.include_usage). */
function sendStream(response, model, content) {
  const id = completionId();
  const created = Math.floor(Date.now() / MILLISECONDS_PER_SECOND);
  response.writeHead(HTTP_OK, {
    'Cache-Control': 'no-cache',
    Connection: 'keep-alive',
    'Content-Type': 'text/event-stream',
  });
  response.write(`data: ${JSON.stringify({
    id,
    object: 'chat.completion.chunk',
    created,
    model,
    choices: [{ index: 0, delta: { role: 'assistant', content }, finish_reason: null }],
  })}\n\n`);
  response.write(`data: ${JSON.stringify({
    id,
    object: 'chat.completion.chunk',
    created,
    model,
    choices: [{ index: 0, delta: {}, finish_reason: 'stop' }],
    usage: usageBlock(),
  })}\n\n`);
  response.end('data: [DONE]\n\n');
}

function sendCompletion(response, model, content) {
  sendJson(response, HTTP_OK, {
    id: completionId(),
    object: 'chat.completion',
    created: Math.floor(Date.now() / MILLISECONDS_PER_SECOND),
    model,
    choices: [{
      index: 0,
      message: { role: 'assistant', content },
      finish_reason: 'stop',
    }],
    usage: usageBlock(),
  });
}

/**
 * Bearer check. The stub is a credential-presenting double, not a credential
 * bypass: without the exact configured key the gateway's screener/turn calls
 * fail exactly as they would against a real provider.
 *
 * @param {import('node:http').IncomingMessage} request
 */
function isAuthorized(request) {
  const header = request.headers.authorization;
  if (typeof header !== 'string') return false;
  const match = /^Bearer\s+(.+)$/u.exec(header.trim());
  return match?.[1]?.trim() === apiKey;
}

async function readJsonBody(request) {
  const chunks = [];
  let size = 0;
  for await (const chunk of request) {
    size += chunk.length;
    if (size > MAX_REQUEST_BYTES) throw new Error('request body is too large');
    chunks.push(Buffer.from(chunk));
  }
  const parsed = JSON.parse(Buffer.concat(chunks).toString('utf8'));
  if (!parsed || typeof parsed !== 'object' || Array.isArray(parsed)) {
    throw new Error('chat completion request must be a JSON object');
  }
  return parsed;
}

/** The two fixture model ids, echoed back as an OpenAI-style catalog. */
function modelCatalog() {
  const created = Math.floor(Date.now() / MILLISECONDS_PER_SECOND);
  return {
    object: 'list',
    data: ['smoke-stub-chat', 'smoke-stub-background'].map(id => ({
      id,
      object: 'model',
      created,
      owned_by: 'psfn-smoke-provider-stub',
    })),
  };
}

const server = createServer((request, response) => {
  const path = (request.url ?? '/').split('?', 1)[0];

  if (request.method === 'GET' && path === '/health') {
    request.resume();
    response.writeHead(HTTP_NO_CONTENT).end();
    return;
  }
  if (!isAuthorized(request)) {
    request.resume();
    sendError(response, HTTP_UNAUTHORIZED, 'missing or invalid bearer credential');
    return;
  }
  if (request.method === 'GET' && path === '/v1/models') {
    request.resume();
    sendJson(response, HTTP_OK, modelCatalog());
    return;
  }
  if (request.method !== 'POST' || path !== '/v1/chat/completions') {
    request.resume();
    sendError(response, HTTP_NOT_FOUND, `unsupported route ${request.method ?? 'UNKNOWN'} ${path}`);
    return;
  }

  readJsonBody(request)
    .then((body) => {
      const model = typeof body.model === 'string' ? body.model : 'smoke-stub-chat';
      const content = resolveResponseContent(body);
      if (body.stream === true) sendStream(response, model, content);
      else sendCompletion(response, model, content);
    })
    .catch((error) => {
      const message = error instanceof Error ? error.message : String(error);
      const status = message.includes('too large') ? HTTP_PAYLOAD_TOO_LARGE : HTTP_BAD_REQUEST;
      sendError(response, status, message);
    });
});

server.listen(Number(portValue), host, () => {
  console.log('[provider-stub] ready; deterministic OpenAI-compatible smoke double');
});

function close() {
  server.close(() => process.exit(0));
}

process.on('SIGTERM', close);
process.on('SIGINT', close);
