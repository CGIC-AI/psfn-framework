// ── Model price book (lomm1) ──
// Gateway-owned current prices. On the owner-file cadence
// (models.json `pricing.catalogRefresh`) it re-reads every enabled slot's
// upstream provider price from the OpenRouter catalogue, keeps the last good
// quote per slot with its fetch time, persists them so a restart does not
// start cold, and reports any slot left without a usable price. It answers
// `ModelPriceBookPort.resolve`, which every ledger estimate and budget
// admission reads through `model-budget.ts`.

import { existsSync, readFileSync } from 'node:fs';
import type {
  CanonicalModelRegistry,
  CanonicalProviderRegistry,
  ModelRegistryEntry,
  ModelRegistryPricingPolicy,
} from '../../../shared/contracts/runtime.js';
import {
  emitHealthEvent,
  hashHealthEventSubject,
  processObserverId,
  stableHealthConditionCorrelationId,
  type HealthEventCode,
  type HealthEventPublisher,
} from '../../../shared/contracts/health-event.js';
import { createComponentLogger } from '../../../shared/logger.js';
import { writeJsonAtomic } from '../../../shared/utils/fs.js';
import { isRecord } from '../../../shared/utils/types.js';
import type { ModelUsageCostRates } from '../../../shared/telemetry/model-usage-accounting.js';
import {
  resolveCatalogReference,
  resolveOwnerCostRates,
  resolveSlotPrice,
  type CatalogPriceQuote,
  type ModelPriceBookPort,
  type ResolvedSlotPrice,
} from './slot-price.js';
import {
  fetchUpstreamEndpointPrice,
  type UpstreamEndpointPriceFailure,
} from './upstream-endpoint-price.js';

const log = createComponentLogger('ModelPriceBook');

const SNAPSHOT_SCHEMA_VERSION = 1;
/** Generated by the gateway beside the owner files; never hand-edited. */
export const MODEL_PRICE_SNAPSHOT_FILE_NAME = 'model-price-snapshot.json';
const MINUTE_MS = 60_000;
const RATE_KEYS = ['inputPer1MUsd', 'outputPer1MUsd', 'cacheReadPer1MUsd', 'cacheWritePer1MUsd'] as const;

/** What the operator sees for one slot. */
export interface ModelPriceStatus {
  slotKey: string;
  provider: string;
  model: string;
  source: ResolvedSlotPrice['source'];
  rates?: ResolvedSlotPrice['rates'];
  catalogModel?: string;
  upstreamProvider?: string;
  endpointTag?: string;
  fetchedAtMs?: number;
  lastAttemptAtMs?: number;
  lastFailure?: UpstreamEndpointPriceFailure;
  catalogUnavailable?: ResolvedSlotPrice['catalogUnavailable'];
  /**
   * The models.json `cost` disagrees with the catalogue price in use. The
   * upstream provider's catalogue price is what is booked; the owner price is
   * shown so the owner can correct or drop it.
   */
  ownerPriceDiffers?: { owner: ModelUsageCostRates };
}

export interface ModelPriceRefreshSummary {
  attempted: number;
  refreshed: number;
  failed: number;
  unknown: number;
}

interface ModelPriceBookConfig {
  modelRegistry?: CanonicalModelRegistry;
  providerRegistry?: CanonicalProviderRegistry;
}

export interface ModelPriceBookOptions {
  /** Live config: models.json may be reloaded in place. */
  config: ModelPriceBookConfig;
  /** Where the last good quotes survive a restart; absent keeps them in memory only. */
  snapshotPath?: string;
  fetch?: typeof fetch;
  now?: () => number;
}

/**
 * The catalogue is read from the configured OpenRouter provider's models API.
 * It is public, so a provider entry kept only for its catalogue (no routed
 * slot, disabled for dispatch) still serves it.
 */
function catalogApiUrl(providerRegistry: CanonicalProviderRegistry | undefined): string | undefined {
  return providerRegistry?.providers.find(provider => (
    provider.type === 'openrouter' && typeof provider.modelsApiUrl === 'string' && provider.modelsApiUrl.trim() !== ''
  ))?.modelsApiUrl;
}

function isQuote(value: unknown): value is CatalogPriceQuote {
  if (!isRecord(value) || !isRecord(value.rates)) return false;
  const rates = value.rates;
  return typeof value.slotKey === 'string'
    && typeof value.catalogModel === 'string'
    && typeof value.upstreamProvider === 'string'
    && typeof value.endpointTag === 'string'
    && typeof value.fetchedAtMs === 'number' && Number.isFinite(value.fetchedAtMs)
    && typeof value.cacheReadListed === 'boolean'
    && typeof value.cacheWriteListed === 'boolean'
    && rates.currency === 'USD'
    && RATE_KEYS.every(key => (
      typeof rates[key] === 'number' && Number.isFinite(rates[key]) && (rates[key] as number) >= 0
    ));
}

export class ModelPriceBook implements ModelPriceBookPort {
  private readonly quotes = new Map<string, CatalogPriceQuote>();
  private readonly attempts = new Map<string, { atMs: number; failure?: UpstreamEndpointPriceFailure }>();
  private readonly fetchImpl: typeof fetch;
  private readonly now: () => number;
  private timer: NodeJS.Timeout | undefined;
  private started = false;
  /** Bumped on every start, so a cycle begun before a restart never schedules another. */
  private generation = 0;
  private refreshing: Promise<ModelPriceRefreshSummary> | undefined;

  constructor(private readonly options: ModelPriceBookOptions) {
    this.fetchImpl = options.fetch ?? ((input, init) => globalThis.fetch(input, init));
    this.now = options.now ?? Date.now;
    this.loadSnapshot();
  }

  private get policy(): ModelRegistryPricingPolicy | undefined {
    return this.options.config.modelRegistry?.pricing;
  }

  resolve(entry: ModelRegistryEntry, atMs: number): ResolvedSlotPrice {
    return resolveSlotPrice({
      entry,
      providerRegistry: this.options.config.providerRegistry,
      policy: this.policy,
      quote: this.quotes.get(entry.id),
      atMs,
    });
  }

  status(atMs = this.now()): ModelPriceStatus[] {
    return (this.options.config.modelRegistry?.models ?? [])
      .filter(entry => entry.enabled !== false)
      .map((entry) => {
        const resolved = this.resolve(entry, atMs);
        const reference = resolveCatalogReference(entry, this.options.config.providerRegistry);
        const attempt = this.attempts.get(entry.id);
        const quote = this.quotes.get(entry.id);
        const owner = resolveOwnerCostRates(entry);
        const differingOwner = resolved.source === 'catalog' && owner
          && RATE_KEYS.some(key => owner[key] !== undefined && owner[key] !== resolved.rates?.[key])
          ? owner
          : undefined;
        return {
          slotKey: entry.id,
          provider: entry.identity.provider,
          model: entry.identity.model,
          source: resolved.source,
          ...(resolved.rates ? { rates: resolved.rates } : {}),
          ...(reference ? { catalogModel: reference.catalogModel, upstreamProvider: reference.upstreamProvider } : {}),
          ...(quote ? { endpointTag: quote.endpointTag, fetchedAtMs: quote.fetchedAtMs } : {}),
          ...(attempt ? { lastAttemptAtMs: attempt.atMs } : {}),
          ...(attempt?.failure ? { lastFailure: attempt.failure } : {}),
          ...(resolved.catalogUnavailable ? { catalogUnavailable: resolved.catalogUnavailable } : {}),
          ...(differingOwner ? { ownerPriceDiffers: { owner: differingOwner } } : {}),
        };
      });
  }

  /** One refresh pass over every enabled slot with a catalogue reference; concurrent calls share it. */
  refresh(health?: HealthEventPublisher): Promise<ModelPriceRefreshSummary> {
    this.refreshing ??= this.runRefresh(health).finally(() => {
      this.refreshing = undefined;
    });
    return this.refreshing;
  }

  /** Refresh now and then every `catalogRefresh.intervalMinutes`, read afresh each time. */
  start(health: HealthEventPublisher): void {
    if (this.timer || this.started) return;
    if (!this.policy?.catalogRefresh.enabled) {
      log.warn('Model catalogue price refresh is off: slots are booked at their models.json cost only', {
        reason: this.policy ? 'pricing.catalogRefresh.enabled is false' : 'models.json has no pricing.catalogRefresh block',
      });
    }
    this.generation += 1;
    const generation = this.generation;
    const tick = (): void => {
      void this.refresh(health)
        .catch((error: unknown) => {
          log.error('Model price refresh failed', { error: error instanceof Error ? error.message : String(error) });
        })
        .finally(() => {
          const intervalMinutes = this.policy?.catalogRefresh.enabled
            ? this.policy.catalogRefresh.intervalMinutes
            : undefined;
          if (!this.started || generation !== this.generation || intervalMinutes === undefined) return;
          this.timer = setTimeout(tick, intervalMinutes * MINUTE_MS);
          this.timer.unref();
        });
    };
    this.started = true;
    tick();
  }

  stop(): void {
    this.started = false;
    if (this.timer) clearTimeout(this.timer);
    this.timer = undefined;
  }

  /** After models.json changed: refresh now and follow the (possibly new) cadence from here. */
  restart(health: HealthEventPublisher): void {
    this.stop();
    this.start(health);
  }

  private async runRefresh(health: HealthEventPublisher | undefined): Promise<ModelPriceRefreshSummary> {
    const summary: ModelPriceRefreshSummary = { attempted: 0, refreshed: 0, failed: 0, unknown: 0 };
    const entries = (this.options.config.modelRegistry?.models ?? []).filter(entry => entry.enabled !== false);
    const apiUrl = catalogApiUrl(this.options.config.providerRegistry);
    if (this.policy?.catalogRefresh.enabled) {
      for (const entry of entries) {
        const reference = resolveCatalogReference(entry, this.options.config.providerRegistry);
        if (!reference) continue;
        summary.attempted += 1;
        const atMs = this.now();
        const result = apiUrl
          ? await fetchUpstreamEndpointPrice(this.fetchImpl, apiUrl, reference)
          : { ok: false as const, failure: 'fetch_failed' as const };
        if (result.ok) {
          this.quotes.set(entry.id, {
            slotKey: entry.id,
            ...reference,
            endpointTag: result.price.endpointTag,
            rates: result.price.rates,
            cacheReadListed: result.price.cacheReadListed,
            cacheWriteListed: result.price.cacheWriteListed,
            fetchedAtMs: atMs,
          });
          this.attempts.set(entry.id, { atMs });
          summary.refreshed += 1;
          continue;
        }
        this.attempts.set(entry.id, { atMs, failure: result.failure });
        summary.failed += 1;
        log.warn('Model price refresh failed for slot', {
          slotKey: entry.id,
          catalogModel: reference.catalogModel,
          upstreamProvider: reference.upstreamProvider,
          failure: result.failure,
          ...(apiUrl ? {} : { reason: 'no openrouter provider with modelsApiUrl in providers.json' }),
        });
        await this.report(health, 'model_price_refresh_failed', entry.id, atMs);
      }
      this.saveSnapshot();
    }
    const nowMs = this.now();
    for (const status of this.status(nowMs)) {
      if (status.source !== 'unknown') continue;
      summary.unknown += 1;
      await this.report(health, 'model_price_unknown', status.slotKey, nowMs, status.catalogUnavailable === 'stale');
    }
    log.info('Model prices', {
      ...summary,
      slots: this.status(nowMs).map(status => ({
        slotKey: status.slotKey,
        source: status.source,
        ...(status.endpointTag ? { endpointTag: status.endpointTag } : {}),
        ...(status.rates ? { rates: status.rates } : {}),
        ...(status.fetchedAtMs !== undefined ? { fetchedAt: new Date(status.fetchedAtMs).toISOString() } : {}),
        ...(status.lastFailure ? { lastFailure: status.lastFailure } : {}),
        ...(status.ownerPriceDiffers ? { ownerPriceDiffers: status.ownerPriceDiffers.owner } : {}),
      })),
    });
    return summary;
  }

  private async report(
    health: HealthEventPublisher | undefined,
    code: Extract<HealthEventCode, 'model_price_refresh_failed' | 'model_price_unknown'>,
    slotKey: string,
    observedAtMs: number,
    priceStale?: boolean,
  ): Promise<void> {
    if (!health) return;
    const subjectHash = hashHealthEventSubject(`model_price:${slotKey}`);
    try {
      await emitHealthEvent(health, {
        owner: { kind: 'system' },
        severity: code === 'model_price_unknown' ? 'degraded' : 'warning',
        code,
        correlationId: stableHealthConditionCorrelationId(code, { kind: 'system' }, subjectHash),
        provenance: {
          process: 'gateway',
          component: 'model_pricing',
          observerId: processObserverId(),
          subjectHash,
        },
        observedAtMs,
        ...(priceStale !== undefined ? { evidence: { priceStale } } : {}),
      });
    } catch (error) {
      log.error('Failed to report model price health', {
        code,
        slotKey,
        error: error instanceof Error ? error.message : String(error),
      });
    }
  }

  private loadSnapshot(): void {
    const path = this.options.snapshotPath;
    if (!path || !existsSync(path)) return;
    try {
      const raw = JSON.parse(readFileSync(path, 'utf8')) as unknown;
      if (!isRecord(raw) || raw.schemaVersion !== SNAPSHOT_SCHEMA_VERSION || !Array.isArray(raw.quotes)) {
        log.warn('Ignoring unreadable model price snapshot', { path });
        return;
      }
      for (const quote of raw.quotes) {
        if (isQuote(quote)) this.quotes.set(quote.slotKey, quote);
      }
    } catch (error) {
      log.warn('Ignoring unreadable model price snapshot', {
        path,
        error: error instanceof Error ? error.message : String(error),
      });
    }
  }

  private saveSnapshot(): void {
    const path = this.options.snapshotPath;
    if (!path) return;
    try {
      writeJsonAtomic(path, { schemaVersion: SNAPSHOT_SCHEMA_VERSION, quotes: [...this.quotes.values()] });
    } catch (error) {
      log.error('Failed to persist model price snapshot', {
        path,
        error: error instanceof Error ? error.message : String(error),
      });
    }
  }
}
